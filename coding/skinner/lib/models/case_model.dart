class CaseModel {

  final String name;
  final int age;
  final String gender;
  final String diagnosis;
  final int confidence;
  final String level;
  final String status;
  final String image;

  CaseModel({
    required this.name,
    required this.age,
    required this.gender,
    required this.diagnosis,
    required this.confidence,
    required this.level,
    required this.status,
    required this.image,
  });

}